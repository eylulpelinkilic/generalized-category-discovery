"""Synthetic fixture videos for software verification. NOT research data.

Solid-colour clips (red/green/blue) exercise decoding, sampling with fewer
frames than requested, odd aspect ratios and different frame rates. A
red-then-blue clip exercises temporal transforms, and a corrupt file must be
reported as a failure while staying in every denominator.
"""
from __future__ import annotations

import subprocess
from pathlib import Path

import numpy as np
import pandas as pd

from ovar.benchmark import MANIFEST_COLUMNS, VOCAB_COLUMNS
from ovar.video import tool

BANNER = ("SYNTHETIC FIXTURES - generated by `python -m ovar smoke-test` for software checks only. "
          "Results on these files are not research evidence.\n")

# name, colour(s), width, height, fps, duration_s, label
CLIPS = [
    ("red_a", ["red"], 160, 120, 10, 2.0, "red"),
    ("red_b", ["red"], 120, 160, 25, 1.2, "red"),
    ("green_a", ["green"], 200, 100, 10, 3.0, "green"),
    ("green_short", ["green"], 160, 120, 15, 0.5, "green"),
    ("blue_a", ["blue"], 160, 120, 10, 2.0, "blue"),
    ("blue_tiny", ["blue"], 64, 64, 5, 1.0, "blue"),
    ("red_then_blue", ["red", "blue"], 160, 120, 10, 2.0, "red"),
]
CLASSES = [("red", "familiar"), ("green", "familiar"), ("blue", "unfamiliar")]
DATASET = "fixture_colors"


def _encode(path: Path, colours: list[str], width: int, height: int, fps: int, duration: float):
    cmd = [tool("ffmpeg"), "-nostdin", "-v", "error", "-y"]
    part = duration / len(colours)
    for colour in colours:
        cmd += ["-f", "lavfi", "-i", f"color=c={colour}:s={width}x{height}:r={fps}:d={part}"]
    if len(colours) > 1:
        inputs = "".join(f"[{i}:v]" for i in range(len(colours)))
        cmd += ["-filter_complex", f"{inputs}concat=n={len(colours)}:v=1:a=0[v]", "-map", "[v]"]
    cmd += ["-c:v", "libx264", "-pix_fmt", "yuv420p", "-g", "5", str(path)]
    subprocess.run(cmd, check=True, capture_output=True)


def build(root) -> dict:
    root = Path(root)
    videos = root / "videos"
    videos.mkdir(parents=True, exist_ok=True)
    (root / "README_SYNTHETIC.txt").write_text(BANNER)
    for name, colours, width, height, fps, duration, _ in CLIPS:
        target = videos / f"{name}.mp4"
        if not target.exists():
            _encode(target, colours, width, height, fps, duration)
    broken = videos / "broken.mp4"
    if not broken.exists():
        broken.write_bytes(np.random.default_rng(0).bytes(4096))

    ids = {c: i for i, (c, _) in enumerate(CLASSES)}
    status = dict(CLASSES)
    rows = [(name, label) for name, *_, label in CLIPS] + [("broken", "green")]
    manifest = pd.DataFrame([{
        "dataset_name": DATASET, "video_id": name, "source_group_id": f"{DATASET}:g{k % 3}",
        "source_group_basis": "synthetic", "video_path": f"{name}.mp4", "action_id": ids[label],
        "action_name": label, "category_status": status[label], "split": "synthetic",
        "official_list": "synthetic",
    } for k, (name, label) in enumerate(rows)], columns=MANIFEST_COLUMNS)
    counts = manifest["action_id"].value_counts()
    vocab = pd.DataFrame([{
        "action_id": i, "official_name": c, "text_name": c, "text_name_source": "synthetic",
        "category_status": s, "n_videos": int(counts.get(i, 0)),
    } for i, (c, s) in enumerate(CLASSES)], columns=VOCAB_COLUMNS)
    manifest.to_csv(root / "manifest.csv", index=False)
    vocab.to_csv(root / "vocab.csv", index=False)
    # Centre "actor" boxes on two frames per clip; blue_tiny has none on purpose,
    # so the crop variant must log it as a failure.
    boxes = [{"dataset_name": DATASET, "video_id": name, "frame_index": f, "x1": w * 0.25, "y1": h * 0.25,
              "x2": w * 0.75, "y2": h * 0.75}
             for name, _, w, h, fps, duration, _ in CLIPS if name != "blue_tiny"
             for f in (0, int(fps * duration) - 1)]
    pd.DataFrame(boxes).to_csv(root / "boxes.csv", index=False)
    return {"name": DATASET, "manifest": str(root / "manifest.csv"), "vocab": str(root / "vocab.csv"),
            "root": str(videos), "boxes": str(root / "boxes.csv")}


def experiment(entry: dict, model: dict, paths: dict) -> dict:
    return {
        "run_name": "smoke_fixture", "synthetic": True, "seed": 0, "device": "cpu",
        "model": model, "datasets": [entry], "paths": paths,
        "protocol": {"name": "fixture_16x1x1", "comparison": "synthetic",
                     "sampling": {"method": "tsn_midpoint", "num_frames": 16, "num_views": 1},
                     "spatial": {"preset": "clip_center", "size": 224},
                     "prompts": {"template_set": "fixture_color"}},
    }
